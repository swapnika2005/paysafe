import api from "../axios";
export const authApi = {
  register:          (data)    => api.post("/auth/register", data),
  login:             (data)    => api.post("/auth/login", data),
  verifyLoginOtp:     (data)    => api.post("/auth/login/verify-otp", data),
  resendLoginOtp:     (challenge_token) => api.post("/auth/login/resend-otp", { challenge_token }),
  updateTwoFactor:   (enabled) => api.patch("/auth/two-factor", { enabled }),
  logout:            ()        => api.post("/auth/logout"),
  refresh:           ()        => api.post("/auth/refresh"),
  me:                ()        => api.get("/auth/me"),
  sendOtp:           (type)    => api.post("/auth/send-otp", { type }),
  verifyOtp:         (code, type) => api.post("/auth/verify-otp", { code, type }),
  changePassword:    (data)    => api.post("/auth/change-password", data),
  forgotPassword:    (phone)   => api.post("/auth/forgot-password", { phone }),
  resetPassword:     (data)    => api.post("/auth/reset-password", data),
  changePin:         (data)    => api.post("/auth/pin/change", data),
  verifyPin:         (pin)     => api.post("/auth/pin/verify", { pin }),
  getSessions:       ()        => api.get("/auth/sessions"),
  revokeSession:     (id)      => api.delete(`/auth/sessions/${id}`),
  revokeAllSessions: ()        => api.delete("/auth/sessions"),
};